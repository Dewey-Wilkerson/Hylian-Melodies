"""The generic AppImage: one file holding the game, its launcher and the libraries a host may lack.

It is built in a Debian 12 container (podman or Docker), never on the host itself:
- generic: Debian 12's C library (2.36, 2022) is old enough that the result starts on every current distro, and the
  CPU level is always x86-64-v2;
- immutable systems (SteamOS, Bazzite, Fedora Silverblue ...) cannot install the build packages, but ship podman.

The host side (ContainerFlow in installer/flow.py) builds the container image once and runs each step of the
ordinary flow inside it (`python3 -m installer.flow --inside`); this module holds what both sides share: the image,
the container command, the AppDir and the AppImage, and putting the result in the menu.

Libraries: everything the game executable loads is copied in, except the C library, the C++ runtime and the graphics
stack (Vulkan, GL, DRM), which must be the host's own. Each copied library sits in its own folder under usr/lib, and
AppRun puts a folder on the library path only when the host has no library of that name, so a host library always
wins over the copy (its graphics driver may load the same libraries in a newer version).

THE APPIMAGE CONTAINS THE GAME: it is for the computer's owner only and must never be shared.
"""

import hashlib
import os
import shutil
import subprocess
import urllib.request

from . import deps, pack

NAME = 'Hylian-Melodies-x86_64.AppImage'
DESKTOP_ID = 'hylian-melodies-appimage'  # (a menu entry of its own: a system package's entry may be there too)

# The AppImage type-2 runtime (AppImage/type2-runtime, MIT): the small static program at the front of the file that
# mounts the image (FUSE) and starts AppRun. Fetched at a pinned release and checked, never vendored.
RUNTIME_URL = 'https://github.com/AppImage/type2-runtime/releases/download/20251108/runtime-x86_64'
RUNTIME_SHA256 = '2fca8b443c92510f1483a883f60061ad09b46b978b2631c807cd873a47ec260d'

# Never copied in: the C library, the C++ runtime (the host's is newer, and its graphics driver needs that one) and
# the graphics stack, which only the host's own driver can provide.
HOST_ONLY = ('ld-linux', 'libc.so', 'libm.so', 'libmvec.so', 'libdl.so', 'libpthread.so', 'librt.so', 'libresolv.so',
             'libutil.so', 'libanl.so', 'libnsl.so', 'libBrokenLocale.so', 'libstdc++.so', 'libgcc_s.so',
             'libvulkan.so', 'libGL.so', 'libGLX', 'libEGL', 'libGLdispatch', 'libOpenGL', 'libGLES', 'libdrm',
             'libgbm.so')

APPRUN = r'''#!/bin/sh
# AppRun: the AppImage's entry point. The package's launcher (usr/bin/hylian-melodies), pointed at the game inside
# this image; it keeps the player's folder in ${XDG_DATA_HOME:-~/.local/share}/hylian-melodies as for the package.
# A copied library (usr/lib/<name>/) is used only when this system has no library of that name.
here=$(dirname "$(readlink -f "$0")")
have=$( (ldconfig -p || /sbin/ldconfig -p || /usr/sbin/ldconfig -p) 2>/dev/null)
tab=$(printf '\t')
libs=
for d in "$here"/usr/lib/*/; do
    n=${d%/}
    n=${n##*/}
    case $have in
        *"$tab$n (libc6,x86-64"*) ;;
        *) libs=$libs${libs:+:}${d%/} ;;
    esac
done
if [ -n "$libs" ]; then
    export LD_LIBRARY_PATH="$libs${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
fi
export HM_GAME_DIR="$here/opt/hylian-melodies"
export HM_SUPPORT_DIR="$here/usr/share/hylian-melodies-recomp"
exec "$here/usr/bin/hylian-melodies" "$@"
'''


class AppImageError(Exception):
    pass


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


# ------------------------------------------------------------------ the container (host side)

def containerfile():
    pkgs = ' '.join(deps.container_packages())
    return (f'# generated by installer/appimage.py: the build container of the generic AppImage\n'
            f'FROM {deps.CONTAINER_BASE}\n'
            'RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends '
            f'{pkgs} && rm -rf /var/lib/apt/lists/*\n')


def image_tag():
    """The image's name: changes whenever its recipe does, so a changed package list builds a new one."""
    return 'localhost/hylian-melodies-builder:' + hashlib.sha256(containerfile().encode()).hexdigest()[:12]


def image_exists(engine, tag):
    cmd = [engine, 'image', 'exists', tag] if engine == 'podman' else [engine, 'image', 'inspect', tag]
    return run(cmd).returncode == 0


def build_image_cmd(engine, tag, context):
    return [engine, 'build', '--pull=missing' if engine == 'podman' else '--pull', '-t', tag, '-f',
            os.path.join(context, 'Containerfile'), context]


def mounts(plan, repo, toolchain):
    """-> [(host path, read_only)]: everything the build inside reads or writes, at the same path as outside."""
    out = [(repo, True)]
    for p in (plan.base, plan.keys, plan.update):
        if p:
            out.append((p, True))
    for d in (plan.work, plan.out, toolchain):
        out.append((d, False))
    return out


def run_cmd(engine, tag, plan, repo, toolchain, args, uid=None, gid=None):
    """The `podman run` / `docker run` command for one step inside the container (args: after `python3`)."""
    uid = os.getuid() if uid is None else uid
    gid = os.getgid() if gid is None else gid
    cmd = [engine, 'run', '--rm', '-i', '--security-opt', 'label=disable']  # (SELinux: no relabelling of your files)
    cmd += ['--userns=keep-id'] if engine == 'podman' else ['--user', f'{uid}:{gid}']
    for path, ro in mounts(plan, repo, toolchain):
        if ':' in path:
            raise AppImageError(f'A path with ":" in it cannot be given to the container: {path}')
        cmd += ['-v', f'{path}:{path}' + (':ro' if ro else '')]
    cmd += ['-w', repo, '-e', 'HOME=' + os.path.join(plan.work, 'container-home'), '-e', 'PYTHONDONTWRITEBYTECODE=1',
            tag, 'python3', *args]
    return cmd


# ------------------------------------------------------------------ the AppDir and the AppImage (container side)

def fetch_runtime(dest_dir):
    """The pinned type-2 runtime into dest_dir (once; checked every time). -> its path"""
    path = os.path.join(dest_dir, 'runtime-x86_64')

    def good():
        h = hashlib.sha256()
        with open(path, 'rb') as f:
            h.update(f.read())
        return h.hexdigest() == RUNTIME_SHA256
    if os.path.isfile(path) and good():
        return path
    os.makedirs(dest_dir, exist_ok=True)
    try:
        with urllib.request.urlopen(RUNTIME_URL, timeout=60) as r, open(path + '.part', 'wb') as f:
            shutil.copyfileobj(r, f)
    except OSError as e:
        raise AppImageError(f'Could not download the AppImage runtime ({RUNTIME_URL}): {e}') from None
    os.replace(path + '.part', path)
    if not good():
        os.remove(path)
        raise AppImageError('The downloaded AppImage runtime does not match its pinned SHA-256; nothing was built')
    return path


def host_only(soname):
    return any(soname.startswith(p) for p in HOST_ONLY)


def libraries(exe):
    """-> {soname: path} of every library the executable loads (ldd: the whole tree), minus the host-only ones."""
    r = run(['ldd', exe])
    if r.returncode:
        raise AppImageError('ldd failed: ' + (r.stderr or r.stdout).strip())
    out, missing = {}, []
    for ln in r.stdout.splitlines():
        f = ln.split()
        if len(f) >= 3 and f[1] == '=>':
            name = os.path.basename(f[0])  # (the loader is listed by its path)
            if f[2] == 'not':
                missing.append(name)
            elif f[2].startswith('/') and not host_only(name):
                out[name] = f[2]
    if missing:
        raise AppImageError('the game executable needs libraries the build container lacks: ' + ' '.join(missing))
    return out


def bundle(exe, libdir):
    """Copy the libraries in, each in a folder named after it (AppRun picks the folders). -> the sonames"""
    libs = libraries(exe)
    for soname, path in sorted(libs.items()):
        d = os.path.join(libdir, soname)
        os.makedirs(d, exist_ok=True)
        shutil.copy2(os.path.realpath(path), os.path.join(d, soname))
        os.chmod(os.path.join(d, soname), 0o755)
    return sorted(libs)


def make_appdir(stage, repo, appdir, settings=None):
    """The package's tree (installer/pack.py) plus AppRun, the copied libraries and the AppImage's own menu entry and
    icon at the top. -> the icon's path inside appdir"""
    pack.build_root(stage, repo, appdir, settings)
    os.remove(os.path.join(appdir, pack.SUPPORT, 'desktop-copy'))  # (the package's hooks only)
    bundle(os.path.join(appdir, pack.GAME, 'hylian-melodies'), os.path.join(appdir, 'usr', 'lib'))
    with open(os.path.join(appdir, 'AppRun'), 'w') as f:
        f.write(APPRUN)
    os.chmod(os.path.join(appdir, 'AppRun'), 0o755)
    shutil.copy(os.path.join(repo, 'packaging', 'hylian-melodies.desktop'),
                os.path.join(appdir, 'hylian-melodies.desktop'))
    icons = os.path.join(appdir, 'usr', 'share', 'icons', 'hicolor')
    icon = next(os.path.join(d, f) for d, _, files in os.walk(icons) for f in files if f.startswith('hylian-melodies'))
    top = os.path.join(appdir, os.path.basename(icon))
    shutil.copy(icon, top)
    os.symlink(os.path.basename(icon), os.path.join(appdir, '.DirIcon'))
    return top


def squash(appdir, runtime, target):
    """mksquashfs the AppDir (zstd, which the type-2 runtime reads) behind the runtime: the AppImage file."""
    img = target + '.squashfs'
    if os.path.exists(img):
        os.remove(img)
    r = run(['mksquashfs', appdir, img, '-root-owned', '-noappend', '-no-xattrs', '-no-progress', '-comp', 'zstd'])
    if r.returncode:
        raise AppImageError('mksquashfs failed: ' + (r.stderr or r.stdout).strip()[-2000:])
    tmp = target + '.part'
    with open(tmp, 'wb') as out:
        for part in (runtime, img):
            with open(part, 'rb') as f:
                shutil.copyfileobj(f, out, 1 << 22)
    os.remove(img)
    os.chmod(tmp, 0o755)
    os.replace(tmp, target)
    return target


def build(stage, repo, out, work, toolchain, settings=None):
    """-> (the AppImage, its icon beside it for the menu entry)"""
    os.makedirs(out, exist_ok=True)
    appdir = os.path.join(work, 'AppDir')
    shutil.rmtree(appdir, ignore_errors=True)
    try:
        runtime = fetch_runtime(os.path.join(toolchain, 'appimage-runtime'))
        icon = make_appdir(stage, repo, appdir, settings)
        side = os.path.join(out, 'hylian-melodies-icon' + os.path.splitext(icon)[1])
        shutil.copy(icon, side)
        target = squash(appdir, runtime, os.path.join(out, NAME))
    except pack.PackError as e:
        raise AppImageError(str(e)) from None
    finally:
        shutil.rmtree(appdir, ignore_errors=True)
    return target, side


# ------------------------------------------------------------------ the player's menu (host side)

def apps_dir(env=None):
    env = os.environ if env is None else env
    return os.path.join(env.get('HOME', ''), 'Applications')


def _data(env):
    base = env.get('XDG_DATA_HOME', '')
    return base if base.startswith('/') else os.path.join(env.get('HOME', ''), '.local', 'share')


def desktop_entry(appimage, icon):
    q = '"' + ''.join('\\' + c if c in '"`$\\' else c for c in appimage) + '"'
    return ('[Desktop Entry]\nType=Application\nName=Hylian Melodies\n'
            'Comment=Native Linux build of your own copy of the rhythm game (personal use)\n'
            f'Exec={q}\nTryExec={appimage}\nIcon={icon}\nTerminal=false\nCategories=Game;\n'
            'StartupWMClass=hylian-melodies\nActions=Fullscreen;\n\n'
            f'[Desktop Action Fullscreen]\nName=Play fullscreen\nExec={q} --fullscreen\n')


def install(appimage, icon, env=None):
    """Move the AppImage into ~/Applications and give it a menu entry and icon (the player's own, nothing
    system-wide; no root). -> {'file', 'files': [everything put in place]}"""
    env = os.environ if env is None else env
    dest = os.path.join(apps_dir(env), NAME)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    if os.path.abspath(appimage) != dest:
        shutil.move(appimage, dest)
    os.chmod(dest, 0o755)
    files = [dest]
    if icon and os.path.isfile(icon):
        ext = os.path.splitext(icon)[1]
        sub = 'scalable' if ext == '.svg' else '256x256'
        icon_dest = os.path.join(_data(env), 'icons', 'hicolor', sub, 'apps', DESKTOP_ID + ext)
        os.makedirs(os.path.dirname(icon_dest), exist_ok=True)
        shutil.move(icon, icon_dest)
        files.append(icon_dest)
    entry = os.path.join(_data(env), 'applications', DESKTOP_ID + '.desktop')
    os.makedirs(os.path.dirname(entry), exist_ok=True)
    with open(entry, 'w') as f:
        f.write(desktop_entry(dest, DESKTOP_ID))
    files.append(entry)
    return {'file': dest, 'files': files}


def remove(files):
    """Delete what install() put in place (the player's saves and settings are elsewhere and stay). -> the removed"""
    gone = []
    for p in files:
        try:
            os.remove(p)
            gone.append(p)
        except FileNotFoundError:
            pass
    return gone
